 (ID,Description,YieldType,YieldChange,TilesRequired,AdjacentFeature)
 SELECT 'MNS_'||f.FeatureType,'LOC_MNS_SPECIAL_ADJACENCY','YIELD_FAITH',
 CAST(s.Value AS INTEGER),1,f.FeatureType FROM Features f
 JOIN MNS_Settings s ON s.Name=CASE
 WHEN f.FeatureType='FEATURE_VOLCANO' THEN 'VolcanoBonusFaith'
 WHEN f.FeatureType='FEATURE_GEOTHERMAL_FISSURE' THEN 'GeothermalBonusFaith'
 ELSE 'FloodplainBonusFaith' END
 WHERE f.FeatureType IN ('FEATURE_VOLCANO','FEATURE_GEOTHERMAL_FISSURE','FEATURE_FLOODPLAINS','FEATURE_FLOODPLAINS_GRASSLAND','FEATURE_FLOODPLAINS_PLAINS');
